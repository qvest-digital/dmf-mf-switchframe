package main

import (
	"context"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

func (d db) dumpStatus(ctx context.Context, itemsDir string) (string, error) {
	claimRows, err := d.sqldb.QueryContext(ctx, `
		SELECT item_id, agent_id, COALESCE(intent, ''), claimed_at FROM claims ORDER BY claimed_at`)
	if err != nil {
		return "", err
	}
	defer claimRows.Close()
	type cl struct {
		ID, Agent, Intent string
		TS                int64
	}
	var claims []cl
	for claimRows.Next() {
		var c cl
		if err := claimRows.Scan(&c.ID, &c.Agent, &c.Intent, &c.TS); err != nil {
			return "", err
		}
		claims = append(claims, c)
	}

	claimed := map[string]bool{}
	for _, c := range claims {
		claimed[c.ID] = true
	}

	items, err := walkItems(itemsDir)
	if err != nil {
		return "", err
	}
	ready := map[string][]item{}
	blocked := []item{}
	for _, it := range items {
		if claimed[it.ID] || it.Status == "done" {
			continue
		}
		if it.Status == "blocked" {
			blocked = append(blocked, it)
			continue
		}
		ready[it.Priority] = append(ready[it.Priority], it)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Switchframe — Status Board\n\n*Auto-generated by sf-team dump-status at %s*\n\n",
		time.Now().Format("2006-01-02 15:04"))

	fmt.Fprintln(&b, "## In Progress")
	if len(claims) == 0 {
		fmt.Fprintln(&b, "*nothing in progress*")
	}
	for _, c := range claims {
		fmt.Fprintf(&b, "- %s (%s): %s\n", c.ID, c.Agent, c.Intent)
	}
	fmt.Fprintln(&b)

	for _, p := range []string{"P0", "P1", "P2", "P3"} {
		list := ready[p]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].ID < list[j].ID })
		fmt.Fprintf(&b, "## Ready — %s\n", p)
		for _, it := range list {
			fmt.Fprintf(&b, "- %s  %s  (%s)\n", it.ID, it.Title, it.Estimate)
		}
		fmt.Fprintln(&b)
	}

	if len(blocked) > 0 {
		fmt.Fprintln(&b, "## Blocked")
		for _, it := range blocked {
			fmt.Fprintf(&b, "- %s  %s\n", it.ID, it.Title)
		}
	}

	return b.String(), nil
}

func walkItems(dir string) ([]item, error) {
	var out []item
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}
		it, perr := parseItemFile(path)
		if perr != nil {
			return nil
		}
		out = append(out, it)
		return nil
	})
	return out, err
}

func runDumpStatus(args []string) int {
	args = reorderFlags(args, nil)
	fset := flag.NewFlagSet("dump-status", flag.ExitOnError)
	items := fset.String("items", "docs/backlog/items", "path to items directory")
	out := fset.String("out", "-", "output path ('-' for stdout)")
	_ = fset.Parse(args)

	ctx, sqldb, _, cleanup, code := setupDBAndIdentity()
	if cleanup != nil {
		defer cleanup()
	}
	if code != 0 {
		return code
	}
	d := newDB(sqldb)
	s, err := d.dumpStatus(ctx, *items)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 4
	}
	if *out == "-" {
		fmt.Print(s)
		return 0
	}
	if err := os.WriteFile(*out, []byte(s), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 4
	}
	return 0
}
