package asr

import "math"

// Whisper mel spectrogram parameters.
// Whisper uses n_fft=400 (window size) but torch.stft zero-pads to 512 for FFT.
// The mel filterbank operates on n_fft//2+1 = 201 frequency bins.
const (
	melSampleRate = 16000 // Input sample rate in Hz
	melFFTSize    = 400   // Window size (25ms at 16kHz)
	melHopLength  = 160   // Hop length (10ms at 16kHz)
	melNFFT       = 512   // FFT size (zero-padded from 400, power of 2 for radix-2)
	melNMels      = 80    // Number of mel filter banks
	melMaxFrames  = 3000  // Max frames (30s of audio)
	melMaxSamples = melSampleRate * 30 // 480000 samples for 30s
	melNBins      = melFFTSize/2 + 1   // 201 FFT bins (based on n_fft=400, NOT 512)
)

// melFilterRange stores the non-zero range of a mel filter to skip zero
// multiplications in the filterbank dot product.
type melFilterRange struct {
	startBin int
	endBin   int // exclusive
	weights  []float32
}

// MelSpectrogram computes Whisper-compatible log-mel spectrograms.
// It holds precomputed Hann window, mel filterbank, and FFT twiddle factors
// so that repeated calls to Compute() avoid redundant setup work.
//
// MelSpectrogram is not goroutine-safe; callers must synchronize access
// or use one instance per goroutine.
type MelSpectrogram struct {
	hannWindow [melFFTSize]float32
	melFilters [melNMels]melFilterRange

	// FFT precomputed data (512-point radix-2 Cooley-Tukey)
	twiddleRe [melNFFT / 2]float32
	twiddleIm [melNFFT / 2]float32
	fftBitrev [melNFFT]uint16

	// Scratch buffers (reused across Compute calls)
	fftRe [melNFFT]float32
	fftIm [melNFFT]float32
}

// NewMelSpectrogram creates a new mel spectrogram computer with precomputed
// Hann window, mel filterbank, and FFT twiddle factors.
func NewMelSpectrogram() *MelSpectrogram {
	m := &MelSpectrogram{}
	m.initHannWindow()
	m.initMelFilterbank()
	m.initFFT()
	return m
}

// initHannWindow precomputes the Hann window: 0.5 * (1 - cos(2*pi*n/N))
func (m *MelSpectrogram) initHannWindow() {
	for n := 0; n < melFFTSize; n++ {
		m.hannWindow[n] = float32(0.5 * (1.0 - math.Cos(2.0*math.Pi*float64(n)/float64(melFFTSize))))
	}
}

// hzToMel converts frequency in Hz to the mel scale.
func hzToMel(hz float64) float64 {
	return 2595.0 * math.Log10(1.0+hz/700.0)
}

// melToHz converts mel scale value back to Hz.
func melToHz(mel float64) float64 {
	return 700.0 * (math.Pow(10.0, mel/2595.0) - 1.0)
}

// initMelFilterbank loads Whisper's exact precomputed mel filterbank from
// the embedded whisperMelFilters array and converts to sparse ranges.
// Using Whisper's exact filterbank (generated by librosa with Slaney
// normalization) is critical — any deviation produces garbage output.
func (m *MelSpectrogram) initMelFilterbank() {
	for f := 0; f < melNMels; f++ {
		row := whisperMelFilters[f]

		// Find the non-zero range for sparse dot product.
		startBin := -1
		endBin := 0
		for bin := 0; bin < melNBins; bin++ {
			if row[bin] != 0 {
				if startBin == -1 {
					startBin = bin
				}
				endBin = bin + 1
			}
		}
		if startBin == -1 {
			startBin = 0
			endBin = 0
		}

		weights := make([]float32, endBin-startBin)
		copy(weights, row[startBin:endBin])

		m.melFilters[f] = melFilterRange{
			startBin: startBin,
			endBin:   endBin,
			weights:  weights,
		}
	}
}

// initFFT precomputes twiddle factors and bit-reversal permutation
// for a 512-point radix-2 Cooley-Tukey FFT.
func (m *MelSpectrogram) initFFT() {
	n := melNFFT
	halfN := n / 2

	// Precompute twiddle factors: W(k,N) = exp(-2*pi*i*k/N)
	// Only need first half (the butterfly only uses indices 0..N/2-1).
	for k := 0; k < halfN; k++ {
		angle := -2.0 * math.Pi * float64(k) / float64(n)
		m.twiddleRe[k] = float32(math.Cos(angle))
		m.twiddleIm[k] = float32(math.Sin(angle))
	}

	// Precompute bit-reversal permutation
	log2N := 9 // log2(512)
	for i := 0; i < n; i++ {
		rev := 0
		v := i
		for b := 0; b < log2N; b++ {
			rev = (rev << 1) | (v & 1)
			v >>= 1
		}
		m.fftBitrev[i] = uint16(rev)
	}
}

// fft512 computes a 512-point FFT in-place on m.fftRe and m.fftIm.
func (m *MelSpectrogram) fft512() {
	re := &m.fftRe
	im := &m.fftIm

	// Bit-reversal permutation
	for i := 0; i < melNFFT; i++ {
		j := int(m.fftBitrev[i])
		if i < j {
			re[i], re[j] = re[j], re[i]
			im[i], im[j] = im[j], im[i]
		}
	}

	// Iterative Cooley-Tukey butterfly stages (9 stages for N=512)
	for s := uint(1); s <= 9; s++ {
		groupSize := 1 << s
		halfGroup := groupSize >> 1
		twStride := melNFFT >> s // = N / groupSize

		for groupStart := 0; groupStart < melNFFT; groupStart += groupSize {
			for k := 0; k < halfGroup; k++ {
				twIdx := k * twStride
				twRe := m.twiddleRe[twIdx]
				twIm := m.twiddleIm[twIdx]

				evenIdx := groupStart + k
				oddIdx := evenIdx + halfGroup

				oRe := re[oddIdx]
				oIm := im[oddIdx]
				tRe := twRe*oRe - twIm*oIm
				tIm := twRe*oIm + twIm*oRe

				eRe := re[evenIdx]
				eIm := im[evenIdx]
				re[evenIdx] = eRe + tRe
				im[evenIdx] = eIm + tIm
				re[oddIdx] = eRe - tRe
				im[oddIdx] = eIm - tIm
			}
		}
	}
}

// Compute produces a Whisper-compatible [80][3000] log-mel spectrogram
// from the given PCM samples (mono float32 at 16kHz).
//
// Matches Whisper's Python implementation exactly:
//   - Reflect padding of n_fft//2 = 200 samples on each side (torch.stft center=True)
//   - 400-point DFT (naive, matching torch.stft n_fft=400)
//   - 201 frequency bins (n_fft//2 + 1)
//   - Whisper's precomputed 80×201 mel filterbank
//   - Log10 with 1e-10 floor, clamp to [max-8, max], normalize (v+4)/4
func (m *MelSpectrogram) Compute(samples []float32) [][]float32 {
	// Truncate or zero-pad input to 30s.
	n := len(samples)
	if n > melMaxSamples {
		n = melMaxSamples
	}
	audio := make([]float32, melMaxSamples)
	copy(audio, samples[:n])

	// Reflect padding: n_fft//2 = 200 samples on each side.
	// This matches torch.stft(center=True) which uses reflect padding.
	padLen := melFFTSize / 2 // 200
	paddedLen := padLen + melMaxSamples + padLen
	padded := make([]float32, paddedLen)
	// Left reflect: audio[padLen, padLen-1, ..., 1] (reflect from index 1, not 0)
	// Matches np.pad(mode='reflect') / torch.stft(center=True) behavior.
	for i := 0; i < padLen; i++ {
		padded[i] = audio[padLen-i]
	}
	// Center: audio
	copy(padded[padLen:], audio)
	// Right reflect: audio[len-2, len-3, ..., len-padLen-1]
	for i := 0; i < padLen; i++ {
		padded[padLen+melMaxSamples+i] = audio[melMaxSamples-2-i]
	}

	// Allocate output: [melNMels][melMaxFrames]
	output := make([][]float32, melNMels)
	for i := range output {
		output[i] = make([]float32, melMaxFrames)
	}

	// Precompute DFT twiddle factors for 400-point DFT, 201 output bins.
	// W(k,n) = exp(-2πi·k·n/N), we need cos and sin for k=0..200, n=0..399.
	// Store per-bin: twRe[k][n] = cos(-2π·k·n/400), twIm[k][n] = sin(-2π·k·n/400)
	// To save memory, compute on the fly using the angle.

	// Scratch for windowed frame and power spectrum.
	var windowed [melFFTSize]float32
	var power [melNBins]float32

	// Process each frame.
	for frame := 0; frame < melMaxFrames; frame++ {
		offset := frame * melHopLength

		// Apply Hann window.
		src := padded[offset : offset+melFFTSize]
		for i := 0; i < melFFTSize; i++ {
			windowed[i] = src[i] * m.hannWindow[i]
		}

		// 400-point DFT: compute first 201 bins (DC to Nyquist).
		// X[k] = sum_{n=0}^{N-1} x[n] * exp(-2πi·k·n/N)
		// |X[k]|² = Re²+Im²
		for k := 0; k < melNBins; k++ {
			var sumRe, sumIm float64
			for n := 0; n < melFFTSize; n++ {
				angle := -2.0 * math.Pi * float64(k) * float64(n) / float64(melFFTSize)
				sumRe += float64(windowed[n]) * math.Cos(angle)
				sumIm += float64(windowed[n]) * math.Sin(angle)
			}
			power[k] = float32(sumRe*sumRe + sumIm*sumIm)
		}

		// Apply mel filterbank using sparse ranges and log scale.
		for mel := 0; mel < melNMels; mel++ {
			filt := &m.melFilters[mel]
			energy := float32(0)
			pw := power[filt.startBin:filt.endBin]
			w := filt.weights
			for i, p := range pw {
				energy += p * w[i]
			}
			if energy < 1e-10 {
				energy = 1e-10
			}
			output[mel][frame] = float32(math.Log10(float64(energy)))
		}
	}

	// Whisper normalization (from whisper/audio.py):
	//   log_spec = torch.maximum(log_spec, log_spec.max() - 8.0)
	//   log_spec = (log_spec + 4.0) / 4.0
	maxVal := float32(-math.MaxFloat32)
	for mel := 0; mel < melNMels; mel++ {
		for _, v := range output[mel] {
			if v > maxVal {
				maxVal = v
			}
		}
	}
	clampMin := maxVal - 8.0
	for mel := 0; mel < melNMels; mel++ {
		row := output[mel]
		for i, v := range row {
			if v < clampMin {
				v = clampMin
			}
			row[i] = (v + 4.0) * 0.25
		}
	}

	return output
}
